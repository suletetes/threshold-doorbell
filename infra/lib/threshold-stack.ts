// ThresholdStack — the Threshold backend on AWS.
//
// Builds, in one stack:
//   - a VPC (2 AZs, the L3 construct's default public + private subnets)
//   - an Application Load Balancer (public, HTTPS-ready, WebSocket-capable)
//   - an ECS Fargate service on ARM64 / Graviton2 (1 task, 0.5 vCPU / 1 GB)
//   - the backend Docker image built from ../backend and pushed to ECR
//   - three Secrets Manager secrets injected into the task
//   - a task role scoped to InvokeModel on Nova Micro only
//
// WebSocket support: the ALB passes the Connection: Upgrade / Upgrade: websocket
// handshake natively; the only tuning needed is a long idle timeout so the
// 10-minute /asr/stream sessions are not cut off (asrMaxSessionMs = 600_000).

import * as cdk from 'aws-cdk-lib';
import { Construct } from 'constructs';
import * as ec2 from 'aws-cdk-lib/aws-ec2';
import * as ecs from 'aws-cdk-lib/aws-ecs';
import * as ecsPatterns from 'aws-cdk-lib/aws-ecs-patterns';
import * as elbv2 from 'aws-cdk-lib/aws-elasticloadbalancingv2';
import * as iam from 'aws-cdk-lib/aws-iam';
import * as logs from 'aws-cdk-lib/aws-logs';
import * as secretsmanager from 'aws-cdk-lib/aws-secretsmanager';

export class ThresholdStack extends cdk.Stack {
  constructor(scope: Construct, id: string, props?: cdk.StackProps) {
    super(scope, id, props);

    const region = cdk.Stack.of(this).region;

    // --- VPC: 2 AZs. The L3 construct below creates one NAT gateway by default;
    // cap maxAzs at 2 and natGateways at 1 to keep demo cost down (one NAT at
    // ~$33/mo is the price of letting the private-subnet task reach Bedrock,
    // Transcribe, and ECR). ---
    const vpc = new ec2.Vpc(this, 'ThresholdVpc', {
      maxAzs: 2,
      natGateways: 1,
    });

    // --- ECS cluster ---
    const cluster = new ecs.Cluster(this, 'ThresholdCluster', {
      vpc,
      containerInsightsV2: ecs.ContainerInsights.ENABLED,
    });

    // --- Application secrets (generated, strong; demo env requires strong
    // secrets because assertStrongSecret runs for every deployable env). The
    // values are generated by Secrets Manager and never appear in the template
    // or in source. Ring client secret is a placeholder for demo (FixtureRing
    // ignores it); replace its value when real Ring credentials exist. ---
    const sessionSecret = new secretsmanager.Secret(this, 'SessionSecret', {
      secretName: 'threshold/session-secret',
      description: 'Threshold app-to-backend session signing secret.',
      generateSecretString: {
        passwordLength: 48,
        excludePunctuation: true,
      },
    });

    const webhookHmacKey = new secretsmanager.Secret(this, 'WebhookHmacKey', {
      secretName: 'threshold/webhook-hmac-key',
      description: 'Threshold Ring webhook HMAC signing key.',
      generateSecretString: {
        passwordLength: 48,
        excludePunctuation: true,
      },
    });

    const ringClientSecret = new secretsmanager.Secret(this, 'RingClientSecret', {
      secretName: 'threshold/ring-client-secret',
      description: 'Ring OAuth client secret (placeholder for demo; replace for live Ring).',
      generateSecretString: {
        passwordLength: 48,
        excludePunctuation: true,
      },
    });

    // --- Log group with a short retention so demo logs do not accumulate cost ---
    const logGroup = new logs.LogGroup(this, 'ThresholdLogGroup', {
      logGroupName: '/ecs/threshold-backend',
      retention: logs.RetentionDays.TWO_WEEKS,
      removalPolicy: cdk.RemovalPolicy.DESTROY,
    });

    // --- Fargate service behind a public ALB (the L3 construct wires VPC,
    // cluster, task definition, service, ALB, target group, and health check) ---
    const service = new ecsPatterns.ApplicationLoadBalancedFargateService(
      this,
      'ThresholdService',
      {
        cluster,
        desiredCount: 1,
        cpu: 512, // 0.5 vCPU
        memoryLimitMiB: 1024, // 1 GB
        publicLoadBalancer: true,
        // Fail a bad deploy fast (minutes, not up to 3 hours) and roll back.
        circuitBreaker: { rollback: true },
        // With desiredCount 1, keep 100% healthy during a deploy so the single
        // task is replaced by a new healthy one rather than dropped first.
        minHealthyPercent: 100,
        maxHealthyPercent: 200,
        // ARM64 / Graviton2: 20% cheaper, 40% better price-performance.
        runtimePlatform: {
          cpuArchitecture: ecs.CpuArchitecture.ARM64,
          operatingSystemFamily: ecs.OperatingSystemFamily.LINUX,
        },
        taskImageOptions: {
          // CDK builds the ARM Docker image from ../backend and pushes to ECR
          // automatically on deploy. Requires Docker running locally.
          image: ecs.ContainerImage.fromAsset('../backend', {
            platform: cdk.aws_ecr_assets.Platform.LINUX_ARM64,
          }),
          containerPort: 8080,
          environment: {
            THRESHOLD_ENV: 'demo',
            AWS_REGION: region,
            BEDROCK_REGION: region,
            HOST: '0.0.0.0',
            PORT: '8080',
            // Allow browser WebSocket connections from the Vercel visitor page.
            // Without this, any request with an Origin header is rejected by
            // isOriginAllowed() in ws-auth.ts (MED-34).
            WS_ALLOWED_ORIGINS: 'https://spike-rho-sepia.vercel.app',
          },
          secrets: {
            SESSION_SECRET: ecs.Secret.fromSecretsManager(sessionSecret),
            WEBHOOK_HMAC_KEY: ecs.Secret.fromSecretsManager(webhookHmacKey),
            RING_CLIENT_SECRET: ecs.Secret.fromSecretsManager(ringClientSecret),
          },
          logDriver: ecs.LogDrivers.awsLogs({
            streamPrefix: 'threshold',
            logGroup,
          }),
        },
      },
    );

    // --- Health check: the backend exposes GET /ready (app.ts). The default
    // health check path is "/", which returns 404 here, so point it at /ready. ---
    service.targetGroup.configureHealthCheck({
      path: '/ready',
      healthyHttpCodes: '200',
      interval: cdk.Duration.seconds(30),
      timeout: cdk.Duration.seconds(5),
      healthyThresholdCount: 2,
      unhealthyThresholdCount: 3,
    });

    // --- WebSocket tuning: the /asr/stream session can run up to 10 minutes
    // (asrMaxSessionMs = 600_000). Raise the ALB idle timeout above that so a
    // live caption session is never dropped by the load balancer. ---
    service.loadBalancer.setAttribute('idle_timeout.timeout_seconds', '605');

    // --- Fast rollout: short deregistration delay so redeploys are quick in a
    // demo (default is 300s). ---
    service.targetGroup.setAttribute('deregistration_delay.timeout_seconds', '10');

    // --- IAM: grant the task role InvokeModel on Nova Micro ONLY (least
    // privilege). The model id is validated-available on this account. ---
    service.taskDefinition.taskRole.addToPrincipalPolicy(
      new iam.PolicyStatement({
        sid: 'BedrockNovaMicroInvoke',
        effect: iam.Effect.ALLOW,
        actions: ['bedrock:InvokeModel'],
        resources: [
          `arn:aws:bedrock:${region}::foundation-model/amazon.nova-micro-v1:0`,
        ],
      }),
    );

    // --- HTTPS listener (port 443) using an imported self-signed cert.
    // This fixes the mixed-content block that prevents the HTTPS Vercel visitor
    // page from opening WebSocket connections to the HTTP-only ALB.
    //
    // The cert covers the ELB DNS name and was imported to ACM with:
    //   aws acm import-certificate --certificate fileb://cert.pem --private-key fileb://key.pem
    //
    // Browsers will show a certificate warning for the self-signed cert, which
    // is acceptable for a hackathon demo. Replace with a proper ACM-managed cert
    // (via a custom domain + DNS validation) before any public launch.
    const cert = elbv2.ListenerCertificate.fromArn(
      'arn:aws:acm:us-east-1:356650046555:certificate/46651a29-3336-42b3-ac7c-aaba0f1a9c93',
    );

    service.loadBalancer.addListener('HTTPS', {
      port: 443,
      open: true,
      certificates: [cert],
      defaultAction: elbv2.ListenerAction.forward([service.targetGroup]),
    });

    // Redirect HTTP → HTTPS so any http:// link auto-upgrades.
    // The L3 pattern already created the HTTP:80 listener as
    // `service.listener`; replace its default action with a redirect.
    service.listener.addAction('RedirectToHTTPS', {
      priority: 1,
      conditions: [elbv2.ListenerCondition.pathPatterns(['/*'])],
      action: elbv2.ListenerAction.redirect({
        port: '443',
        protocol: 'HTTPS',
        permanent: true,
      }),
    });

    // --- Outputs ---
    new cdk.CfnOutput(this, 'AlbDnsName', {
      value: service.loadBalancer.loadBalancerDnsName,
      description: 'Public ALB DNS. Backend is now reachable over HTTPS.',
    });

    new cdk.CfnOutput(this, 'ReadyUrl', {
      value: `https://${service.loadBalancer.loadBalancerDnsName}/ready`,
      description: 'Health check URL (HTTPS). Should return {"ready":true}.',
    });

    new cdk.CfnOutput(this, 'SignalingWsUrl', {
      value: `wss://${service.loadBalancer.loadBalancerDnsName}/signaling`,
      description: 'Secure WebSocket signaling endpoint for the live session.',
    });
  }
}
